const STRINGS: Record<Lang, Record<StringKey, string>> = { en, kn, hi };

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let text = STRINGS[lang]?.[key] ?? en[key] ?? key;
  if (text.includes('|') && vars && typeof vars.n === 'number') {
    const [one, many] = text.split('|');
    text = vars.n === 1 ? one : many;
  }
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`)) : text;
}
