export const TRANSLATIONS: Record<SupportedLanguage, Record<TranslationKey, string>> = { en, kn, hi };

/** Same lookup as the Doctor portal, plus `{name}`-style placeholders. */
export function t(lang: SupportedLanguage, key: TranslationKey, vars?: Record<string, string | number>): string {
  const text = TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
